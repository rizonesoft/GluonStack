#!/usr/bin/env python3
"""Generates the design tokens each surface reads from the one source, docs/design/tokens.json.

    python scripts/generate-ui-tokens.py            write Tokens.xaml (control panel) and tokens.css (web dashboard)
    python scripts/generate-ui-tokens.py --check    exit 1 if either file differs from a fresh generation

A colour, size or spacing value is changed in tokens.json and regenerated, never edited in a generated file or written
as a literal on a control (docs/design/SPEC.md, "Tokens"). Standard library only. Developer tooling: never shipped.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "design" / "tokens.json"
NOTICE = "Generated by scripts/generate-ui-tokens.py from docs/design/tokens.json. Do not edit."


def pascal(name):
    return "".join(part.capitalize() for part in name.split("-"))


def control_folder():
    for name in ("gluon-control", "iso-control"):
        if (ROOT / name).is_dir():
            return ROOT / name
    raise SystemExit("no control panel folder (gluon-control or iso-control)")


def xaml(tokens):
    lines = ['<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
             '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
             '                    xmlns:sys="clr-namespace:System;assembly=System.Runtime">',
             f"    <!-- {NOTICE} -->"]
    for name, value in tokens["color"].items():
        lines.append(f'    <Color x:Key="{pascal(name)}Color">{value}</Color>')
        lines.append(f'    <SolidColorBrush x:Key="{pascal(name)}Brush" Color="{value}"/>')
    # Fonts are the files linked into the project from assets/fonts; the name after # is the family inside them.
    for name, family in tokens["font"].items():
        lines.append(f'    <FontFamily x:Key="{pascal(name)}Font">pack://application:,,,/assets/fonts/#{family}</FontFamily>')
    for name, value in tokens["size"].items():
        lines.append(f'    <sys:Double x:Key="{pascal(name)}Size">{value}</sys:Double>')
    for name, value in tokens["weight"].items():
        lines.append(f'    <FontWeight x:Key="{pascal(name)}Weight">{value}</FontWeight>')
    for name, value in tokens["space"].items():
        lines.append(f'    <sys:Double x:Key="Space{name}">{value}</sys:Double>')
        lines.append(f'    <Thickness x:Key="Space{name}Thickness">{value}</Thickness>')
    for name, value in tokens["radius"].items():
        lines.append(f'    <CornerRadius x:Key="{pascal(name)}Radius">{value}</CornerRadius>')
    for name, value in tokens["border"].items():
        lines.append(f'    <Thickness x:Key="{pascal(name)}Border">{value}</Thickness>')
    for name, value in tokens["layout"].items():
        lines.append(f'    <sys:Double x:Key="{pascal(name)}">{value}</sys:Double>')
    lines.append("</ResourceDictionary>")
    return "\n".join(lines) + "\n"


def css(tokens):
    lines = [f"/* {NOTICE} */"]
    faces = [("Space Grotesk", 600, "SpaceGrotesk-SemiBold.ttf"), ("Space Grotesk", 700, "SpaceGrotesk-Bold.ttf"),
             ("JetBrains Mono", 400, "JetBrainsMono-Regular.ttf"), ("JetBrains Mono", 500, "JetBrainsMono-Medium.ttf")]
    for family, weight, file in faces:
        lines.append(f'@font-face {{ font-family: "{family}"; font-weight: {weight}; font-display: swap; '
                     f'src: url("fonts/{file}") format("truetype"); }}')
    lines.append(":root {")
    for name, value in tokens["color"].items():
        lines.append(f"  --{name}: {value};")
    lines.append(f'  --font-heading: "{tokens["font"]["heading"]}", system-ui, sans-serif;')
    lines.append(f'  --font-body: "{tokens["font"]["body"]}", ui-monospace, monospace;')
    for group, prefix, unit in (("size", "size-", "px"), ("weight", "weight-", ""), ("space", "space-", "px"),
                                ("radius", "radius-", "px"), ("border", "border-", "px"), ("layout", "", "px")):
        for name, value in tokens[group].items():
            lines.append(f"  --{prefix}{name}: {value}{unit};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    outputs = {control_folder() / "Themes" / "Tokens.xaml": xaml(tokens),
               ROOT / "default" / "assets" / "tokens.css": css(tokens)}
    stale = []
    for path, text in outputs.items():
        if "--check" in argv:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", path.relative_to(ROOT).as_posix())
    if stale:
        print("stale (run python scripts/generate-ui-tokens.py):", *stale, sep="\n  ")
        return 1
    if "--check" in argv:
        print("design tokens are current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
